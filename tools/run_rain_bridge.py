"""R.A.I.N.–CIRCLE research bridge: proposals in, validated experiments out.

R.A.I.N. (github.com/topherchris420/lop-nur-twin) is a deliberation layer
that may *propose* experiments. CIRCLE's deterministic validation, human
authorization, and twin execution decide what actually runs. This tool is the
working bridge between the two sides:

1. **Proposals.** Reads candidate experiment manifests (CIRCLE's
   circle-experiment-protocol/1 form). When R.A.I.N. is not installed, a
   deterministic stand-in proposer generates candidates so the bridge is
   exercisable today; its provenance is recorded as ``stand_in``, never as
   R.A.I.N. output.
2. **Validation.** Every candidate passes through ``models.protocols.validate``
   unchanged: simulation-only targets, mandatory sham arms, held-out seeds,
   tighten-only gates. A proposal that relaxes safety is rejected here.
3. **Execution.** Valid candidates are authorized by a named human reviewer
   and executed against the twin, beside three baselines: the repository's
   human-designed example protocol, a fixed default-controller protocol, and a
   seeded random variant.
4. **Comparison.** Each protocol's PRIMARY outcome is reported against the
   human baseline on shared seeds.

Nothing here lets a proposer override the controller, gates, or consent.

Usage: python tools/run_rain_bridge.py [--candidates N] [--seeds 400 401 ...] [--output PATH]
"""

from __future__ import annotations

import argparse
from dataclasses import replace
import json
from pathlib import Path
import random
import sys
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from models.protocols import ProtocolError, authorize, execute, validate

SCHEMA = "circle-rain-bridge/1"
HUMAN_BASELINE = ROOT / "experiments" / "protocols" / "paced-breathing-arousal.json"
DEFAULT_SEEDS = [400, 401, 402, 403]
REVIEWER = "R.A.I.N. bridge operator"


def stand_in_proposal(index: int, seeds: list[int]) -> dict[str, Any]:
    """A deterministic, clearly labeled stand-in for a R.A.I.N. proposal.

    Varies what a proposer may vary: the cue period, tightened gates, and the
    scenario — never the target, the arms, or the analysis plan.
    """
    rng = random.Random(20261115 + index)
    cue_period_s = rng.choice([8, 9, 10, 11, 12])
    min_beat_coverage = rng.choice([0.7, 0.75, 0.8])
    scenario = rng.choice(["clean", "interrupted"])
    return {
        "schema": "circle-experiment-protocol/1",
        "protocol_id": f"PROTO-A17E{index:04X}",
        "proposed_by": {"kind": "AI_MODEL",
                       "name": "R.A.I.N. bridge stand-in proposer (deterministic; not R.A.I.N.)",
                       "model_version": "stand-in/1"},
        "hypothesis": f"Stand-in proposal {index}: cue period {cue_period_s} s with a tightened beat-coverage "
                     f"gate ({min_beat_coverage}) lowers the recovery arousal proxy versus matched sham.",
        "rationale": "Generated by the deterministic stand-in proposer to exercise the bridge without "
                     "claiming R.A.I.N. authorship.",
        "target": "SIMULATION", "scenario": scenario,
        "arms": [{"id": "ACTIVE", "actuate": True}, {"id": "SHAM", "actuate": False}],
        "intervention": {"kind": "HAPTIC_PACED_BREATHING", "cue_period_s": cue_period_s},
        "decision_rule": {"controller": "CIRCLE_CLOSED_LOOP_CONTROLLER", "overrides": {}},
        "quality_gates": {"min_beat_coverage": min_beat_coverage},
        "outcomes": [
            {"id": "arousal_proxy", "metric": "recovery_arousal_index_mean", "role": "PRIMARY", "direction": "DECREASE"},
            {"id": "motion", "metric": "recovery_motion_fraction", "role": "SAFETY", "direction": "NO_INCREASE"},
        ],
        "seeds": list(seeds),
        "stopping_rule": {"kind": "FIXED_SAMPLE", "note": "Fixed seed pairs, chosen before any run."},
        "analysis_plan": {"test": "PAIRED_SIGN_FLIP_PERMUTATION", "alpha": 0.05, "correction": "HOLM",
                          "exclusions": "None."},
    }


def random_baseline(seed: int, seeds: list[int]) -> dict[str, Any]:
    """A seeded random valid variant: what blind tuning would produce."""
    rng = random.Random(seed)
    return {
        "schema": "circle-experiment-protocol/1",
        "protocol_id": "PROTO-BA5E" + format(seed, "04X"),
        "proposed_by": {"kind": "HUMAN", "name": "seeded random baseline"},
        "hypothesis": "A randomly tuned controller, included so candidate proposals must beat blind tuning.",
        "rationale": "Random search over permitted overrides and gates.",
        "target": "SIMULATION", "scenario": "clean",
        "arms": [{"id": "ACTIVE", "actuate": True}, {"id": "SHAM", "actuate": False}],
        "intervention": {"kind": "HAPTIC_PACED_BREATHING", "cue_period_s": rng.choice([8, 10, 12])},
        "decision_rule": {"controller": "CIRCLE_CLOSED_LOOP_CONTROLLER",
                          "overrides": {"trigger_index": rng.choice([1.6, 2.0, 2.4])}},
        "quality_gates": {},
        "outcomes": [
            {"id": "arousal_proxy", "metric": "recovery_arousal_index_mean", "role": "PRIMARY", "direction": "DECREASE"},
            {"id": "motion", "metric": "recovery_motion_fraction", "role": "SAFETY", "direction": "NO_INCREASE"},
        ],
        "seeds": list(seeds),
        "stopping_rule": {"kind": "FIXED_SAMPLE", "note": "Fixed seed pairs, chosen before any run."},
        "analysis_plan": {"test": "PAIRED_SIGN_FLIP_PERMUTATION", "alpha": 0.05, "correction": "HOLM",
                          "exclusions": "None."},
    }


def _primary(result: dict[str, Any]) -> dict[str, Any]:
    return next(entry for entry in result["tests"].values() if entry["role"] == "PRIMARY")


def run_bridge(candidate_count: int, seeds: list[int]) -> dict[str, Any]:
    # The human-designed baseline defines the comparison point.
    human = json.loads(HUMAN_BASELINE.read_text(encoding="utf-8"))
    human = replace_seeds(human, seeds)
    plans: list[dict[str, Any]] = [("HUMAN_DESIGNED", human)]
    plans.append(("FIXED_DEFAULT", fixed_default(seeds)))
    plans.append(("RANDOM_BASELINE", random_baseline(77, seeds)))
    for index in range(candidate_count):
        plans.append((f"RAIN_STANDIN_{index:02d}", stand_in_proposal(index, seeds)))

    executed, rejected = [], []
    for label, protocol in plans:
        verdict = validate(protocol)
        if verdict["status"] != "VALID_FOR_SIMULATION":
            rejected.append({"label": label, "protocol_id": protocol.get("protocol_id"),
                             "problems": verdict["problems"]})
            continue
        authorization = authorize(protocol, REVIEWER, "2026-11-15")
        result = execute(protocol, authorization)
        primary = _primary(result)
        executed.append({
            "label": label, "protocol_id": protocol["protocol_id"],
            "proposed_by": protocol["proposed_by"]["name"],
            "scenario": protocol["scenario"],
            "intervention": protocol["intervention"], "quality_gates": protocol["quality_gates"],
            "replays_match": result["replays_match"],
            "primary": {"metric": primary["metric"], "direction": primary["direction"],
                        "mean_difference_active_minus_sham": primary["mean_difference_active_minus_sham"],
                        "p_adjusted": primary.get("p_adjusted"), "conclusion": primary["conclusion"]},
            "safety": {key: entry["conclusion"] for key, entry in result["tests"].items()
                       if entry["role"] == "SAFETY"},
        })

    human_primary = next(item["primary"] for item in executed if item["label"] == "HUMAN_DESIGNED")
    for item in executed:
        item["versus_human_baseline"] = {
            "delta_mean_difference": (None if item["primary"]["mean_difference_active_minus_sham"] is None
                                      or human_primary["mean_difference_active_minus_sham"] is None else
                                      round(item["primary"]["mean_difference_active_minus_sham"]
                                            - human_primary["mean_difference_active_minus_sham"], 6)),
            "note": "Negative delta means a larger active-minus-sham decrease than the human-designed baseline "
                    "on these seeds, under the twin's assumed response model.",
        }
    return {"schema": SCHEMA, "seeds": seeds, "reviewer": REVIEWER,
            "proposer": "deterministic stand-in (R.A.I.N. not installed for this run)",
            "executed": executed, "rejected": rejected,
            "interpretation": "All comparisons run under the twin's assumed response model. They exercise "
                              "the proposal path and its validation, not a physiological effect. A proposer "
                              "can never relax gates, arms, or targets; those are validated, not trusted."}


def replace_seeds(protocol: dict[str, Any], seeds: list[int]) -> dict[str, Any]:
    protocol = dict(protocol)
    protocol["seeds"] = list(seeds)
    return protocol


def fixed_default(seeds: list[int]) -> dict[str, Any]:
    """The repository's example protocol shape with default controller values."""
    protocol = json.loads(HUMAN_BASELINE.read_text(encoding="utf-8"))
    protocol = replace_seeds(protocol, seeds)
    protocol["protocol_id"] = "PROTO-F1DE" + "0000"
    protocol["proposed_by"] = {"kind": "HUMAN", "name": "fixed default-controller baseline"}
    protocol["hypothesis"] = "The default controller configuration, as the no-tuning baseline."
    protocol["decision_rule"] = {"controller": "CIRCLE_CLOSED_LOOP_CONTROLLER", "overrides": {}}
    protocol["quality_gates"] = {"min_beat_coverage": 0.7, "max_motion_fraction": 0.2}
    return protocol


def failure_driven_evaluation(seeds: list[int]) -> dict[str, Any]:
    """Discover why CIRCLE fails, propose a correction, prove it on unseen seeds.

    The failure: a rash controller (``trigger_consecutive=1`` — start guidance
    on a single elevated evaluation) acts on evidence the disciplined controller
    would wait out. On the interrupted scenario this is exactly the documented
    failure class that once produced premature guidance. The correction: restore
    the sustained-evidence requirement (``trigger_consecutive=2``). Both arms
    run the same held-out seeds through the same validation and authorization;
    the report keeps whichever conclusion the evidence supports, including a tie.
    """
    def variant(protocol_id: str, consecutive: int, hypothesis: str, by: dict) -> dict[str, Any]:
        return {
            "schema": "circle-experiment-protocol/1", "protocol_id": protocol_id,
            "proposed_by": by, "hypothesis": hypothesis,
            "rationale": "Failure-driven: the rash variant reproduces the premature-guidance failure class; "
                         "the correction restores the sustained-evidence requirement.",
            "target": "SIMULATION", "scenario": "interrupted",
            "arms": [{"id": "ACTIVE", "actuate": True}, {"id": "SHAM", "actuate": False}],
            "intervention": {"kind": "HAPTIC_PACED_BREATHING", "cue_period_s": 10},
            "decision_rule": {"controller": "CIRCLE_CLOSED_LOOP_CONTROLLER",
                             "overrides": {"trigger_consecutive": consecutive}},
            "quality_gates": {},
            "outcomes": [{"id": "arousal_proxy", "metric": "recovery_arousal_index_mean",
                          "role": "PRIMARY", "direction": "DECREASE"},
                         {"id": "holds", "metric": "quality_holds", "role": "SECONDARY",
                          "direction": "DECREASE"}],
            "seeds": list(seeds),
            "stopping_rule": {"kind": "FIXED_SAMPLE", "note": "Held-out seeds, fixed before any run."},
            "analysis_plan": {"test": "PAIRED_SIGN_FLIP_PERMUTATION", "alpha": 0.05, "correction": "HOLM",
                              "exclusions": "None."},
        }

    rash = variant("PROTO-DEAD0001", 1, "A rash controller (single-evaluation trigger) still acts in time on "
                                        "interrupted evidence.", {"kind": "AI_MODEL", "name": "R.A.I.N. failure "
                                        "analysis (stand-in)", "model_version": "stand-in/1"})
    corrected = variant("PROTO-C0DE0002", 2, "Restoring the sustained-evidence requirement (two consecutive "
                                            "evaluations) keeps recovery timing without premature starts.",
                        {"kind": "AI_MODEL", "name": "R.A.I.N. correction proposal (stand-in)",
                         "model_version": "stand-in/1"})
    results = {}
    for label, protocol in (("RASH_VARIANT", rash), ("CORRECTED_VARIANT", corrected)):
        verdict = validate(protocol)
        if verdict["status"] != "VALID_FOR_SIMULATION":
            results[label] = {"validated": False, "problems": verdict["problems"]}
            continue
        executed = execute(protocol, authorize(protocol, REVIEWER, "2026-11-15"))
        results[label] = {"validated": True, "replays_match": executed["replays_match"],
                         "primary": {k: _primary(executed)[k] for k in
                                     ("mean_difference_active_minus_sham", "p_adjusted", "conclusion")}}
    return {"seeds": seeds, "variants": results,
            "interpretation": "The rash variant reproduces a documented CIRCLE failure class; the correction "
                              "is evaluated on the same held-out seeds under identical validation. Whichever "
                              "way the evidence points — including no difference at this sample size — is the "
                              "result. The proposer never edits the gates; the twin and the validator judge."}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--candidates", type=int, default=2, help="stand-in proposals to generate")
    parser.add_argument("--seeds", type=int, nargs="+", default=DEFAULT_SEEDS, help="shared held-out seeds")
    parser.add_argument("--failure-driven", action="store_true",
                        help="add the rash-vs-corrected failure-driven evaluation")
    parser.add_argument("--output", type=Path, default=ROOT / "outputs" / "rain-bridge" / "report.json")
    args = parser.parse_args(argv)
    if set(args.seeds) & set(range(0, 30)):
        parser.error("bridge seeds must be held out (development seeds 0-29 are reserved)")
    report = run_bridge(args.candidates, args.seeds)
    if args.failure_driven:
        report["failure_driven"] = failure_driven_evaluation(args.seeds)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    for item in report["executed"]:
        primary = item["primary"]
        print(f"{item['label']:<18} p={primary['p_adjusted'] if primary['p_adjusted'] is not None else '—'} "
              f"Δmean={primary['mean_difference_active_minus_sham']} ({primary['conclusion']})")
    for item in report["rejected"]:
        print(f"{item['label']:<18} REJECTED: {'; '.join(item['problems'])[:120]}")
    print(f"Report: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
